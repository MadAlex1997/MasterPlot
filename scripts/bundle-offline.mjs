#!/usr/bin/env node
// Builds a self-contained offline-installation bundle for library consumers:
// masterplot's own package tarball + every runtime `dependencies` and
// `peerDependencies` package, as both a vendored node_modules tarball and a
// populated npm cache (usable with `npm install --offline --cache`).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8'));

const bundleDir = path.join(repoRoot, 'offline-bundle');
const stagingDir = path.join(bundleDir, '.staging');
const rawCacheDir = path.join(bundleDir, '.npm-cache');

function run(cmd, args, cwd) {
  console.log(`\n$ ${cmd} ${args.join(' ')}`);
  execFileSync(cmd, args, { cwd, stdio: 'inherit' });
}

function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}

function shQuote(spec) {
  return `'${spec.replace(/'/g, `'\\''`)}'`;
}

console.log(`Building offline dependency bundle for ${pkg.name}@${pkg.version}\n`);

rmrf(bundleDir);
fs.mkdirSync(stagingDir, { recursive: true });
fs.mkdirSync(rawCacheDir, { recursive: true });

// Make sure lib/ (what `npm pack` ships) reflects the current source before packing.
run('npm', ['run', 'build:lib'], repoRoot);

run('npm', ['pack', repoRoot, '--pack-destination', bundleDir], repoRoot);
const tgzName = fs.readdirSync(bundleDir).find((f) => f.endsWith('.tgz'));
if (!tgzName) throw new Error('npm pack did not produce a .tgz file');

// Every package a consumer needs to actually run masterplot: its own
// dependencies plus everything it declares as a peerDependency.
const runtimeDeps = { ...pkg.dependencies, ...pkg.peerDependencies };
const optionalPeers = new Set(Object.keys(pkg.peerDependenciesMeta || {}));

fs.writeFileSync(
  path.join(stagingDir, 'package.json'),
  JSON.stringify(
    {
      name: 'masterplot-offline-deps',
      version: '0.0.0',
      private: true,
      dependencies: runtimeDeps,
    },
    null,
    2
  )
);

// Installing into an isolated cache both resolves+downloads the full
// transitive tree and populates a cache directory npm can reuse offline.
run('npm', ['install', '--cache', rawCacheDir, '--no-audit', '--no-fund'], stagingDir);

run('tar', ['-czf', path.join(bundleDir, 'node_modules.tar.gz'), '-C', stagingDir, 'node_modules'], repoRoot);
run('tar', ['-czf', path.join(bundleDir, 'npm-cache.tar.gz'), '-C', bundleDir, '.npm-cache'], repoRoot);

fs.copyFileSync(path.join(stagingDir, 'package-lock.json'), path.join(bundleDir, 'package-lock.json'));

const installLines = Object.entries(runtimeDeps)
  .map(([name, range]) => `  ${shQuote(`${name}@${range}`)} \\`)
  .join('\n');

const depTable = Object.entries(runtimeDeps)
  .map(([name, range]) => `| \`${name}\` | \`${range}\` | ${optionalPeers.has(name) ? 'optional' : 'required'} |`)
  .join('\n');

fs.writeFileSync(
  path.join(bundleDir, 'INSTALL-OFFLINE.md'),
  `# MasterPlot Offline Installation Bundle

Bundle for **${pkg.name}@${pkg.version}**. Generated by \`npm run bundle:offline\`.

Contents:
- \`${tgzName}\` — the masterplot package itself (same as \`npm pack\` output)
- \`npm-cache.tar.gz\` — a populated npm cache containing masterplot's full
  runtime dependency tree (\`dependencies\` + \`peerDependencies\`)
- \`node_modules.tar.gz\` — the same packages already installed, for a
  drop-in-and-go install with no \`npm\` step at all
- \`package-lock.json\` — resolved versions used to build this bundle, for reference
- \`install-offline.sh\` — installs via the npm-cache method into a target project

## Dependencies included

| Package | Range | |
|---|---|---|
${depTable}

Optional peer dependencies are extra \`@loaders.gl/*\` format loaders and
\`zstd-codec\` — only needed if your app uses those specific loaders.

## Method A (recommended): npm offline cache

Merges cleanly with a project that already has its own dependencies.

\`\`\`bash
./install-offline.sh /path/to/your/project
\`\`\`

Or manually:

\`\`\`bash
BUNDLE=/path/to/bundle          # this directory
CACHE=/path/to/offline-npm-cache  # anywhere you like
mkdir -p "$CACHE"
tar -xzf "$BUNDLE/npm-cache.tar.gz" -C "$CACHE" --strip-components=1

cd /path/to/your/project
npm install --offline --cache "$CACHE" \\
${installLines}
  "$BUNDLE/${tgzName}"
\`\`\`

## Method B: vendored node_modules

Fastest option if your project has no other dependencies yet — no npm
invocation required, just extract:

\`\`\`bash
cd /path/to/your/project
tar -xzf /path/to/bundle/node_modules.tar.gz
tar -xzf /path/to/bundle/${tgzName}
rm -rf node_modules/masterplot && mv package node_modules/masterplot
\`\`\`

Both methods produce a working \`node_modules/masterplot\` plus its runtime
dependencies with zero network access.
`
);

const installScriptDepArgs = Object.entries(runtimeDeps)
  .map(([name, range]) => `  ${shQuote(`${name}@${range}`)} \\`)
  .join('\n');

fs.writeFileSync(
  path.join(bundleDir, 'install-offline.sh'),
  `#!/usr/bin/env bash
# Installs masterplot + its runtime dependencies offline via a populated npm cache.
# Usage: ./install-offline.sh /path/to/your/project
set -euo pipefail
BUNDLE_DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" && pwd)"
TARGET="\${1:?Usage: install-offline.sh <path-to-your-project>}"

CACHE_DIR="$TARGET/.masterplot-offline-cache"
mkdir -p "$CACHE_DIR"
tar -xzf "$BUNDLE_DIR/npm-cache.tar.gz" -C "$CACHE_DIR" --strip-components=1

cd "$TARGET"
npm install --offline --cache "$CACHE_DIR" \\
${installScriptDepArgs}
  "$BUNDLE_DIR/${tgzName}"

echo "masterplot installed offline into $TARGET/node_modules."
echo "You can remove $CACHE_DIR now if you don't need it again."
`
);
fs.chmodSync(path.join(bundleDir, 'install-offline.sh'), 0o755);

rmrf(stagingDir);
rmrf(rawCacheDir);

const finalName = `${pkg.name}-${pkg.version}-offline-bundle.tar.gz`;
run('tar', ['-czf', path.join(repoRoot, finalName), '-C', repoRoot, 'offline-bundle'], repoRoot);

console.log(`\nOffline bundle ready:`);
console.log(`  Directory: ${path.relative(repoRoot, bundleDir)}/`);
console.log(`  Archive:   ${finalName}`);
